    for (final e in _s2t.entries) e.value: e.key,
  };

  /// 简体转繁体。
  static String toTraditional(String input) {
    final buf = StringBuffer();
    for (final ch in input.runes) {
      final s = String.fromCharCode(ch);
      buf.write(_s2t[s] ?? s);
    }
    return buf.toString();
  }

  /// 繁体转简体。
  static String toSimplified(String input) {
    final buf = StringBuffer();
    for (final ch in input.runes) {
      final s = String.fromCharCode(ch);
      buf.write(_t2s[s] ?? s);
    }
    return buf.toString();
  }

